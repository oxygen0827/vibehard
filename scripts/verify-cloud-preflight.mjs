// ONLY for the isolated preflight DB/ports. This simulates Runner messages,
// never model inference. It creates test records and a test project workspace.
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

assert.ok(new URL(process.env.DATABASE_URL).pathname.endsWith("_preflight_20260917"), "Refusing to run outside the isolated preflight database");
const base = "http://127.0.0.1:3211/vibehard";
let cookie = "";
const request = (route, options = {}) => fetch(base + route, { signal: AbortSignal.timeout(15000), ...options, headers: { Cookie: cookie, "Content-Type": "application/json", ...options.headers } });
const envelope = () => ({ protocolVersion: 1, messageId: randomUUID(), timestamp: new Date().toISOString() });
const registration = await request("/api/auth/register", { method: "POST", body: JSON.stringify({
  email: `cloud-check-${randomUUID()}@example.invalid`, password: randomUUID() + randomUUID(), inviteCode: process.env.INVITE_CODES.split(",")[0],
}) });
assert.equal(registration.status, 201, "preflight account registration");
cookie = registration.headers.getSetCookie().map(value => value.split(";")[0]).find(value => value.startsWith("vibehard_session=") && value.length > 50);
assert.ok(cookie);
const projectResponse = await request("/api/projects", { method: "POST", body: JSON.stringify({ name: "Cloud transport preflight", workspaceKey: "preflight" }) });
assert.equal(projectResponse.status, 201);
const { project } = await projectResponse.json();
assert.equal(project.runnerKey, "cloud-runner");
const threadResponse = await request(`/api/projects/${project.id}/threads`, { method: "POST", body: "{}" });
assert.equal(threadResponse.status, 201);
const { thread } = await threadResponse.json();
const runnerResponse = await request("/api/runners/register", { method: "POST", headers: { Authorization: `Bearer ${process.env.RUNNER_REGISTRATION_TOKEN}` }, body: JSON.stringify({ runnerKey: "cloud-runner", name: "Simulated preflight runner", capabilities: ["codex"] }) });
assert.equal(runnerResponse.status, 201);
const { secret } = await runnerResponse.json();
const socket = new WebSocket("ws://127.0.0.1:8788/runner");
let acknowledgements = 0;
const accepted = new Promise((resolve, reject) => {
  socket.addEventListener("error", reject, { once: true });
  socket.addEventListener("open", () => socket.send(JSON.stringify({ ...envelope(), type: "runner.hello", runnerKey: "cloud-runner", instanceId: randomUUID(), secret, capabilities: ["codex"] })));
  socket.addEventListener("message", ({ data }) => {
    const message = JSON.parse(data);
    if (message.type === "runner.accepted") resolve();
    if (message.type === "event.ack") acknowledgements++;
    if (message.type === "task.start") {
      socket.send(JSON.stringify({ ...envelope(), type: "command.ack", runnerKey: "cloud-runner", commandId: message.messageId }));
      for (const [sequence, type] of ["task.started", "agent.message", "task.completed"].entries()) {
        socket.send(JSON.stringify({ ...envelope(), type: "event", runnerKey: "cloud-runner", taskId: message.taskId, threadId: message.threadId,
          event: { eventId: randomUUID(), sequence, timestamp: new Date().toISOString(), type, data: { text: "Simulated transport verification; not a model response" } } }));
      }
    }
  });
});
const watchdog = setTimeout(() => { console.error("Preflight timed out"); process.exit(1); }, 30000);
try {
  await accepted;
  const turnResponse = await request(`/api/threads/${thread.id}/turns`, { method: "POST", body: JSON.stringify({ input: "Transport test only", model: "gpt-5.6-terra", providerId: "openai" }) });
  assert.equal(turnResponse.status, 202);
  let completed = false;
  for (let i = 0; i < 30; i++) {
    const overview = await (await request(`/api/threads/${thread.id}`)).json();
    if (overview.turns.some(turn => turn.status === "completed") && acknowledgements === 3) { completed = true; break; }
    await new Promise(resolve => setTimeout(resolve, 250));
  }
  assert.ok(completed, "task completion and event acknowledgements");
  const workspace = path.join("/var/lib/vibehard-runner/workspaces", project.workspaceKey);
  assert.ok(workspace.startsWith("/var/lib/vibehard-runner/workspaces/"));
  await mkdir(workspace, { recursive: true, mode: 0o700 });
  await writeFile(path.join(workspace, "README.md"), "Synthetic preflight fixture. Not generated by a model.\n", { mode: 0o600 });
  const download = await request(`/api/projects/${project.id}/download`);
  assert.equal(download.status, 200);
  const bytes = new Uint8Array(await download.arrayBuffer());
  assert.equal(Buffer.from(bytes.subarray(0, 4)).toString("hex"), "504b0304");
  assert.ok(download.headers.get("content-disposition").includes(".zip"));
  console.log(JSON.stringify({ registration: true, project: true, runnerTransport: true, eventAcknowledgements: acknowledgements, completed: true, zipDownload: true, modelInferenceTested: false }));
} finally { clearTimeout(watchdog); socket.close(); }
