function esc(value) {
  return String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

function rect(x, y, w, h, fill, radius = 8, stroke = "none") {
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${radius}" fill="${fill}" stroke="${stroke}"/>`;
}

function text(x, y, value, size = 14, color = "#dce7f3", weight = 400, anchor = "start", family = "ui") {
  const font = family === "mono" ? "SFMono-Regular, Menlo, monospace" : "Hiragino Sans GB, PingFang SC, Arial, sans-serif";
  return `<text x="${x}" y="${y}" font-family="${font}" font-size="${size}" font-weight="${weight}" fill="${color}" text-anchor="${anchor}">${esc(value)}</text>`;
}

function line(x1, y1, x2, y2, color = "#263342", strokeWidth = 1, dash = "") {
  return `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${color}" stroke-width="${strokeWidth}" ${dash ? `stroke-dasharray="${dash}"` : ""}/>`;
}

function progressBar(x, y, w, progress, color = "#38bdf8") {
  return `${rect(x, y, w, 6, "#202b37", 3)}${rect(x, y, Math.max(6, w * progress), 6, color, 3)}`;
}

function typing(value, frame, startFrame = 0, endFrame = 5) {
  const ratio = Math.max(0, Math.min(1, (frame - startFrame + 1) / (endFrame - startFrame + 1)));
  const chars = Array.from(value);
  return chars.slice(0, Math.ceil(chars.length * ratio)).join("");
}

function phase(frame) {
  if (frame < 6) return { name: "input", progress: (frame + 1) / 6 };
  if (frame < 12) return { name: "process", progress: (frame - 5) / 6 };
  return { name: "output", progress: (frame - 11) / 6 };
}

